function books(
  home: number,
  draw: number,
  away: number,
  extras: Partial<OddsQuote> = {},
): OddsQuote[] {
  const jitter = (n: number, j: number) => +(n * j).toFixed(2);
  return [
    { bookmaker: "Winamax", home, draw, away, ...extras },
    {
      bookmaker: "Betclic",
      home: jitter(home, 0.98),
      draw: jitter(draw, 1.03),
      away: jitter(away, 1.02),
      ...extras,
    },
    {
      bookmaker: "Unibet",
      home: jitter(home, 1.02),
      draw: jitter(draw, 0.97),
      away: jitter(away, 0.99),
      ...extras,
    },
    {
      bookmaker: "Pinnacle",
      home: jitter(home, 1.04),
      draw: jitter(draw, 1.01),
      away: jitter(away, 1.03),
      ...extras,
    },
    {
      bookmaker: "Bet365",
      home: jitter(home, 0.99),
      draw: jitter(draw, 1.0),
      away: jitter(away, 1.01),
      ...extras,
    },
  ];
}

function match(partial: Omit<Match, "prediction" | "sources" | "status" | "minute" | "score"> & {
  status?: Match["status"];
  minute?: number | null;
  score?: Match["score"];
}): Match {
  const prediction = predict(partial.home.name, partial.away.name);
  return {
    status: partial.status ?? "scheduled",
    minute: partial.minute ?? null,
    score: partial.score ?? { home: null, away: null },
    sources: ["fallback", "model"],
    prediction,
    ...partial,
  };
}

