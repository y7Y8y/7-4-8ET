function row(
  rank: number,
  team: Team,
  played: number,
  w: number,
  d: number,
  l: number,
  gf: number,
  ga: number,
  form: StandingRow["form"],
): StandingRow {
  return {
    rank,
    team,
    played,
    won: w,
    draw: d,
    lost: l,
    gf,
    ga,
    gd: gf - ga,
    pts: w * 3 + d,
    form,
  };
}

